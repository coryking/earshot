#!/usr/bin/env python3
"""Regenerate the AMBE+2 decoder constants in src/ambe/tables/ from the MD-380 firmware.

The decoder in src/ambe is a port of the AMBE+2 decoder in Tytera MD-380 firmware D002.032
(see src/ambe/DESIGN.md). Its constant tables (codebooks, windows, polynomial coefficients)
and the decoder's initial RAM state are copied out of the firmware image and the md380emu RAM
snapshot by this script, so the engine itself never needs the firmware at build or run time.

usage: scripts/ambe-tables.py [MD380_DIR]   (default engine/.native-md380, from fetch-md380.sh)

Each src/ambe/tables/<name>.spec lists the tables for src/ambe/tables/<name>.rs, one per line:
    NAME  address  count  type        # comment
where type is i16, u16, i32, u32, u8 or i8 and address is a firmware (flash 0x0800c000+) or
RAM-snapshot (0x20000000+) address. Lines starting with # are comments.
"""
import hashlib
import pathlib
import struct
import sys

FLASH, SRAM = 0x0800C000, 0x20000000
FW_SHA = "c0351f250a834660641bca3b06be931c80cc1ed0ef808356c550b99cd0f4c632"
RAM_SHA = "d40398183e9aa8db6288a62d9a0e0c233cb143ef5633680abd829cc03c719f66"
FMT = {"i16": ("h", 2), "u16": ("H", 2), "i32": ("i", 4), "u32": ("I", 4), "u8": ("B", 1), "i8": ("b", 1)}

engine = pathlib.Path(__file__).resolve().parent.parent
src = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else engine / ".native-md380"
fw = (src / "firmware/D002.032.bin").read_bytes()
ram = (src / "firmware/d02032-core.img").read_bytes()
assert hashlib.sha256(fw).hexdigest() == FW_SHA, "not the pinned D002.032 image"
assert hashlib.sha256(ram).hexdigest() == RAM_SHA, "not the pinned d02032-core RAM snapshot"


def read(addr, n):
    if FLASH <= addr < FLASH + len(fw):
        return fw[addr - FLASH: addr - FLASH + n]
    if SRAM <= addr < SRAM + len(ram):
        return ram[addr - SRAM: addr - SRAM + n]
    raise ValueError(f"address {addr:#x} outside firmware and RAM snapshot")


for spec in sorted((engine / "src/ambe/tables").glob("*.spec")):
    out = [f"// Generated by scripts/ambe-tables.py from {spec.name}; do not edit.",
           "// Constants copied from Tytera MD-380 firmware D002.032 (proprietary; see src/ambe/DESIGN.md).",
           "#![allow(clippy::unreadable_literal)]", ""]
    for line in spec.read_text().splitlines():
        line = line.split("#", 1)
        comment = line[1].strip() if len(line) > 1 else ""
        fields = line[0].split()
        if not fields:
            continue
        name, addr, count, typ = fields[0], int(fields[1], 16), int(fields[2], 0), fields[3]
        code, size = FMT[typ]
        vals = struct.unpack(f"<{count}{code}", read(addr, count * size))
        if comment:
            out.append(f"/// {comment}")
        out.append(f"/// Firmware address {addr:#010x}, {count} x {typ}.")
        out.append(f"pub const {name}: [{typ}; {count}] = [")
        for i in range(0, count, 12):
            out.append("    " + ", ".join(str(v) for v in vals[i:i + 12]) + ",")
        out.append("];")
        out.append("")
    spec.with_suffix(".rs").write_text("\n".join(out))
    print(f"wrote {spec.with_suffix('.rs').relative_to(engine)}")
